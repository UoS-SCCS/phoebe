module Feldhofer (satKeyLinkFeld, satNameLinkFeld, satKeyWeakLinkFeld, satNameWeakLinkFeld, numTraces, numDone, oneDone) where
import ProtModel
import Data.Tree
import Data.Maybe
import Debug.Trace
import qualified Data.List as L
import qualified Data.Set as S
import HelperFunctions
import LogicSyntax
{-|
Module      : Feldhofer
Description : The Feldhofer symmetric-key RFID mutual-authentication protocol.

Analysed for unlinkability by Hirschi, Baelde and Delaune (JCS 2019) and by
Baelde, Delaune and Moreau (CSF 2020), where it is concluded UNLINKABLE.

    R -> T : nR
    T -> R : {| <nR, nT> |}_k
    R -> T : {| <nT, nR> |}_k

k is a symmetric key shared between the tag T and the reader R.  Mutual
authentication is captured by the matching-receive semantics: the echoed
nonces must be consistent with each party's frame, so no explicit equality
post-conditions are needed.

The message-flow layer (roles / actions below) is exactly what AnB.hs generates
from examples/Feldhofer.anb.

* To change the model size, see
```
maxSessions = 2
numTags     = 2
keys        = [Key (LKey 1), Key (LKey 2)]
```
-}

-- ---------------------------------------------------------------------------
maxSessions = 2
numTags     = 2
keys        = [Key (LKey i) | i <- [1,2]]     -- each tag is bound to its own key (see possibleTags)
tagNames    = [Tag i | i <- [1..numTags]]
readerNames = [Reader 1]
roles       = [R, T]

agents = trace ("tag agents " ++ show (length tagAgents) ++ ", reader agents " ++ show (length readerAgents))
               tagAgents ++ readerAgents

-- ---- message-flow layer (generated by AnB.hs from examples/Feldhofer.anb) --
actions =
    [ Send 1 R true [AbsNonce NR] (AbsNonce NR)
    , Rec  1 T trues              (AbsNonce NR)
    , Send 2 T true [AbsNonce NT] (SCrypt (AbsKey KT) (Pair (AbsNonce NR) (AbsNonce NT)))
    , Rec  2 R trues              (SCrypt (AbsKey KT) (Pair (AbsNonce NR) (AbsNonce NT)))
    , Send 3 R true []            (SCrypt (AbsKey KT) (Pair (AbsNonce NT) (AbsNonce NR)))
    , Rec  3 T trues              (SCrypt (AbsKey KT) (Pair (AbsNonce NT) (AbsNonce NR)))
    ]

spy = Agent
      { _name = Spy, _sess = Nothing, _role = Nothing
      , _iniTerms = [Key (LKey 0)]
      , _iniFrame = []
      , _id = 0
      , _indistActions = [[a] | a <- actions]
      }

feldhofer :: ProtocolSpec
feldhofer = ProtocolSpec
  { _spy = spy
  , _roles = roles
  , _honestAgents = agents
  , _actions = actions
  , _protName = "Feldhofer"
  }

tagAgents :: [Agent]
tagAgents =
    [ Agent
      { _name = nm, _sess = Just sess, _role = Just T, _id = id
      , _iniTerms = [k]
      , _iniFrame = [(AbsName T, Name nm), (AbsKey KT, k)]
      , _indistActions = []
      }
    | ((sess, nm, k), id) <- zip possibleTags [1 ..]
    ]
    where
      -- each tag name is bound to its own long-term key (Tag n <-> LKey n)
      possibleTags =
          [ (sess, Tag n, Key (LKey m))
          | sess <- [1..maxSessions], Tag n <- tagNames, Key (LKey m) <- keys, n == m ]

readerAgents :: [Agent]
readerAgents =
    [ Agent
      { _name = nm, _sess = Just sess, _role = Just R, _id = id
      , _iniTerms = keys
      , _iniFrame = [(AbsName R, Name nm), (AbsList Self, Tuple list), (AbsList (AbsName R), Tuple list)]
      , _indistActions = []
      }
    | ((sess, nm, list), id) <- zip possibleReaders [1]     -- a single reader session
    ]
    where
      possibleReaders =
          [ (sess, nm, keys) | sess <- [1..maxSessions], nm <- readerNames ]

-- ---------------------------------------------------------------------------
-- Unlinkability properties (as for TagReader0)
-- ---------------------------------------------------------------------------

keyLink =  K (UAg spy) (ExistsKey (VarKey "y") (forAllHonest [VarAg "x"] (Link (UVarAg "x") (AbsKey KT, VarKey "y"))))

nameLink = K (UAg spy) (ExistsName (VarName "y") (forAllHonest [VarAg "x"] (Link (UVarAg "x") (AbsName T, VarName "y"))))

nameWeakLink = existsHonest [VarAg "x", VarAg "y"] (UVarAg "x" `plays` T ∧ UVarAg "y" `plays` T ∧ K (UAg spy) (ExistsName (VarName "t") (UVarAg "x" `named` VarName "t" ∧ UVarAg "y" `named` VarName "t" ∧ nEqI (UVarAg "x") (UVarAg "x"))))

keyWeakLink  = existsHonest [VarAg "x", VarAg "y"] (UVarAg "x" `plays` T ∧ UVarAg "y" `plays` T ∧ K (UAg spy) (ExistsKey (VarKey "k") (Link (UVarAg "x") (AbsKey KT, VarKey "k") ∧ Link (UVarAg "y") (AbsKey KT, VarKey "k") ∧ nEqI (UVarAg "x") (UVarAg "x"))))

-- we look at traces with `maxSessions` tag sessions, each having at least sent
-- its identifying message (step 2 = the tag's observable output)
tagsDone tr = length (aliveWithRole T tr) == maxSessions
              && all (\x -> step (_role x) x tr >= 2) (aliveWithRole T tr)

satKeyLinkFeld      = show (justHead [tr | tr <- build feldhofer, truth (feldhofer, build feldhofer, tr) keyLink,      tagsDone tr])
satNameLinkFeld     = show (justHead [tr | tr <- build feldhofer, truth (feldhofer, build feldhofer, tr) nameLink,     tagsDone tr])
satKeyWeakLinkFeld  = show (justHead [tr | tr <- build feldhofer, truth (feldhofer, build feldhofer, tr) keyWeakLink,  tagsDone tr])
satNameWeakLinkFeld = show (justHead [tr | tr <- build feldhofer, truth (feldhofer, build feldhofer, tr) nameWeakLink, tagsDone tr])

numTraces :: Int
numTraces = length (build feldhofer)

numDone :: Int
numDone = length [tr | tr <- build feldhofer, tagsDone tr]

oneDone :: String
oneDone = show (justHead [tr | tr <- build feldhofer, tagsDone tr])
