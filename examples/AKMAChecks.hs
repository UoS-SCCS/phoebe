{-|
Module      : AKMAChecks
Description : Unlinkability of the AKMA key identifier (3GPP TS 33.535), Ua* phase.

Companion of the original module AKMA (options AK1, AK2, AKP1, AKP2, AKA, AKX,
AKNV, AKPNV).  It restates that study in the check framework of Checks.hs and
adds a direct formulation with two requests.  One modelling difference: here
the Fresh identifier is a genuinely fresh short-term value generated by the
send, whereas AKMA.hs gives every request its own long-term constant.

The observable step of AKMA on the Ua* reference point is the application
session establishment request, by which a UE presents its key identifier to an
application function:

    UE -> AF : < AKID , AF_ID >

The core network and the AF-to-core channels are trusted and abstracted away.
The UE plays role T (names t1, t2), its AKID is the slot `AbsKey KT`; the AF is
the name in slot `AbsName R` (names r1, r2).  Three ways of deriving the AKID:

  * Global : one AKID per UE, presented to every AF          (AKMA as specified)
  * PerAf  : one AKID per (UE, AF) pair, fixed over time      (ablation)
  * Fresh  : a new AKID for every request                     (the privacy-preserving variant)

The question is whether the intruder, who sees every request, comes to know
that requests carry the same AKID.
-}
module AKMAChecks where
import ProtModel
import LogicSyntax
import HelperFunctions
import Checks
import Data.Maybe
import qualified Data.List as L

data Akid = Global | PerAf | Fresh deriving (Eq, Show)

ues, afs :: [Int]
ues = [1, 2]
afs = [1, 2]

actionsOf :: Akid -> [Action]
actionsOf d = [ Send 1 T true [AbsKey KT | d == Fresh] (Pair (AbsKey KT) (AbsName R)) ]

spyOf :: Akid -> Agent
spyOf d = Agent
  { _name = Spy, _sess = Nothing, _role = Nothing, _id = 0
  , _iniTerms = [Key (LKey 0)], _iniFrame = []
  , _indistActions = [[a] | a <- actionsOf d] }

-- | one agent per (request slot, UE, target AF)
ueAgents :: Akid -> Int -> [Agent]
ueAgents d nsess =
  [ Agent { _name = Tag u, _sess = Just s, _role = Just T, _id = i
          , _iniTerms = [Name (Tag u), Name (Reader a)] ++ akid u a
          , _iniFrame = [ (Role T, Name (Tag u)), (Self, Name (Tag u)), (AbsName T, Name (Tag u))
                        , (AbsName R, Name (Reader a)) ] ++ [ (AbsKey KT, k) | k <- akid u a ]
          , _indistActions = [] }
  | ((s, u, a), i) <- zip [ (s, u, a) | s <- [1 .. nsess], u <- ues, a <- afs ] [1 ..] ]
  where
    akid u a = case d of
      Global -> [Key (LKey u)]
      PerAf  -> [Key (LKey (10 * u + a))]
      Fresh  -> []

protOf :: Akid -> Int -> ProtocolSpec
protOf d nsess = ProtocolSpec
  { _spy = spyOf d, _roles = [T, R], _honestAgents = ueAgents d nsess
  , _actions = actionsOf d, _protName = "AKMA-" ++ show d ++ "-" ++ show nsess }

-- | The intruder does NOT know that the requests draw their AKIDs from a pool
-- of at most n values.  With n = 1: it does not know that all requests carry
-- one and the same AKID.  With n = (number of requests - 1): the strong
-- unlinkability of CSF'24, by key.
unlinkable :: Akid -> Int -> Stmt
unlinkable d n = Neg (K (UAg (spyOf d))
  (existsKey vars
     (forAllHonest [VarAg "x"]
        (plays (UVarAg "x") T `imp` Disj [ Link (UVarAg "x") (AbsKey KT, v) | v <- vars ]))))
  where vars = [VarKey ("y" ++ show i) | i <- [1 .. n]]

-- | Weak unlinkability of CSF'24, by key: there are no two distinct requests of
-- which the intruder knows that they carry the same AKID.  The two requests are
-- agents, bound outside K; the intruder knows something about them only if it
-- can tell who ran them.
weakUnlinkable :: Akid -> Stmt
weakUnlinkable d = Neg (existsHonest [VarAg "x", VarAg "y"]
  (plays (UVarAg "x") T ∧ plays (UVarAg "y") T
     ∧ K (UAg (spyOf d))
         (existsKey [VarKey "a"]
            (Link (UVarAg "x") (AbsKey KT, VarKey "a")
               ∧ Link (UVarAg "y") (AbsKey KT, VarKey "a")
               ∧ nEqI (UVarAg "x") (UVarAg "y")))))

-- state selectors -------------------------------------------------------------
complete :: Int -> Trace -> Bool
complete nsess tr = length (doneWith T 1 tr) == nsess

-- | all requests completed, and addressed to pairwise distinct AFs
crossAf :: Int -> Trace -> Bool
crossAf nsess tr = complete nsess tr
  && length (L.nub [ t | x <- doneWith T 1 tr, (AbsName R, t) <- frame x tr ]) == nsess

m2, m3 :: Akid -> [Trace]
m2 d = build (protOf d 2)
m3 d = build (protOf d 3)

checks :: [Check]
checks = concat
  [ [ Check ("AK" ++ tag ++ "1") ("AKMA/" ++ show d ++ ", 2 requests") "the intruder does not know two requests share an AKID"
            (protOf d 2) mdl2 (complete 2) (unlinkable d 1) e1
    , Check ("AK" ++ tag ++ "2") ("AKMA/" ++ show d ++ ", 2 requests") "same, requests addressed to two different AFs"
            (protOf d 2) mdl2 (crossAf 2) (unlinkable d 1) e2
    , Check ("AK" ++ tag ++ "3") ("AKMA/" ++ show d ++ ", 3 requests") "strong unlinkability by AKID (CSF'24)"
            (protOf d 3) mdl3 (complete 3) (unlinkable d 2) e3
    , Check ("AK" ++ tag ++ "4") ("AKMA/" ++ show d ++ ", 3 requests") "weak unlinkability by AKID (CSF'24)"
            (protOf d 3) mdl3 (complete 3) (weakUnlinkable d) e4 ]
  | (d, tag, e1, e2, e3, e4) <- [ (Global, "G", False, False, False, False)
                                , (PerAf,  "A", False, True,  False, True)
                                , (Fresh,  "F", True,  True,  True,  True) ]
  , let mdl2 = m2 d, let mdl3 = m3 d ]

sanity :: [String]
sanity =
  [ "AKMA/" ++ show d ++ "/" ++ show n ++ ": states=" ++ show (length m)
      ++ " honest-sends-synthesizable=" ++ show (honestSendsOK m)
      ++ " fresh-distinct=" ++ show (freshDistinct m)
      ++ " complete=" ++ show (length [() | tr <- m, complete n tr])
      ++ " complete-cross-AF=" ++ show (length [() | tr <- m, crossAf n tr])
  | d <- [Global, PerAf, Fresh], (n, m) <- [(2, m2 d), (3, m3 d)] ]
