-- ---------------------------------------------------------------------------
-- Unlinkability properties (as for Basic-Hash)
-- ---------------------------------------------------------------------------

negWeakUnlinkability :: Stmt
negWeakUnlinkability =
  existsHonest [VarAg "x", VarAg "y"]
    (UVarAg "x" `plays` T ∧ UVarAg "y" `plays` T
       ∧ K (UAg spy) (ExistsName (VarName "t")
            (UVarAg "x" `named` VarName "t" ∧ UVarAg "y" `named` VarName "t"
               ∧ nEqI (UVarAg "x") (UVarAg "y"))))

negStrongUnlinkability :: Stmt
negStrongUnlinkability =
  K (UAg spy) (existsName varnames
    (forAllHonest [VarAg "x"]
       (Link (UVarAg "x") (Role T, VarAg "x")
          `imp` Disj [Link (UVarAg "x") (Self, varname) | varname <- varnames])))
  where varnames = [VarName ("y" ++ show i) | i <- [1..(maxSessions-1)]]

-- traces with `maxSessions` tag sessions that have each produced their
-- observable output (step 2 = the tag's answer message)
tagsOut :: Trace -> Bool
tagsOut tr = length (aliveWithRole T tr) == maxSessions
             && all (\x -> step (_role x) x tr >= 2) (aliveWithRole T tr)

satNegWeakUnlinkabilityHL =
  show (justHead [tr | tr <- build hashLock, truth (hashLock, build hashLock, tr) negWeakUnlinkability, tagsOut tr])
satNegStrongUnlinkabilityHL =
  show (justHead [tr | tr <- build hashLock, truth (hashLock, build hashLock, tr) negStrongUnlinkability, tagsOut tr])

numTraces :: Int
numTraces = length (build hashLock)

numDone :: Int
numDone = length [tr | tr <- build hashLock, tagsOut tr]
