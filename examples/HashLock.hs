{-|
Module      : HashLock
Description : The (randomized, reader-nonce) Hash-Lock RFID protocol.

One of the RFID case studies proved UNLINKABLE by Hirschi, Baelde and Delaune
(JCS 2019).  A reader challenges the tag with a fresh nonce; the tag answers
with its own nonce and a keyed hash binding both nonces and its secret key.

    R -> T : nR
    T -> R : <nT, h(<nR, nT, k>)>

The reader identifies the tag by the lookup post-condition `phi` (as in
Basic-Hash).  The message-flow layer below is exactly what AnB.hs generates
from examples/HashLock.anb.

As for Basic-Hash, WEAK unlinkability holds, while the plausibilistic STRONG
notion fails by a pigeonhole argument once the intruder sees more tag sessions
than there are possible tag names.

* To change the model size, see
```
maxSessions = 3
numTags     = 2
```
-}

-- ---------------------------------------------------------------------------
maxSessions = 3
numTags     = 2
keys        = [Key (LKey i) | i <- [1..numTags]]
tagNames    = [Tag i | i <- [1..numTags]]
readerNames = [Reader 1]
roles       = [R, T]

agents = trace ("tag agents " ++ show (length tagAgents) ++ ", reader agents " ++ show (length readerAgents))
               tagAgents ++ readerAgents

-- ---- message-flow layer (generated by AnB.hs from examples/HashLock.anb) ---
actions =
    [ Send 1 R true [AbsNonce NR] (AbsNonce NR)
    , Rec  1 T trues              (AbsNonce NR)
    , Send 2 T true [AbsNonce NT] (Pair (AbsNonce NT) (Hash (Triple (AbsNonce NR) (AbsNonce NT) (AbsKey KT))))
    , Rec  2 R (true, phi)        (Pair (AbsNonce NT) (Hash (Triple (AbsNonce NR) (AbsNonce NT) (AbsKey KT))))
    ]
  where
    -- reader identifies the tag: some key x in its list reproduces the hash
    phi = ExistsKey (VarKey "x")
            ((VarKey "x" ∈ UAbsName R)
               ∧ (Link (UAbsName R)
                    ( Hash (Triple (AbsNonce NR) (AbsNonce NT) (AbsKey KT))
                    , Hash (Triple (Abs (AbsNonce NR)) (Abs (AbsNonce NT)) (VarKey "x")))))

spy = Agent
      { _name = Spy, _sess = Nothing, _role = Nothing
      , _iniTerms = [Key (LKey 0)]
      , _iniFrame = []
      , _id = 0
      , _indistActions = [[a] | a <- actions]
      }

hashLock :: ProtocolSpec
hashLock = ProtocolSpec
  { _spy = spy, _roles = roles, _honestAgents = agents
  , _actions = actions, _protName = "HashLock" }

tagAgents :: [Agent]
tagAgents =
    [ Agent
      { _name = nm, _sess = Just sess, _role = Just T, _id = id
      , _iniTerms = [k, Name nm]
      , _iniFrame = [(Role T, Name nm), (Self, Name nm), (AbsName T, Name nm), (AbsKey KT, k)]
      , _indistActions = []
      }
    | ((sess, nm, k), id) <- zip possibleTags [1 ..]
    ]
    where
      -- each tag name is bound to its own key (Tag n <-> LKey n)
      possibleTags =
          [ (sess, Tag n, Key (LKey m))
          | sess <- [1..maxSessions], Tag n <- tagNames, Key (LKey m) <- keys, n == m ]

